      <h2 id="muayene">Muayene nasıl ilerliyor?</h2>
      <p>İlk görüşme, çoğu hastanın beklediğinden uzun sürer; çünkü alerjide teşhisin büyük kısmı hikâyeden çıkar. Sorular ayrıntılıdır: Şikayetiniz hangi ayda artıyor? Evde halı, yorgan, evcil hayvan var mı? İş yerinizde toz, koku ya da kimyasal maruziyeti oluyor mu? Şikayet sabah mı, gece mi ağırlaşıyor?</p>
      <ol class="steps" style="margin:1.5rem 0">
        <li>
          <span class="step-n">1</span>
          <h3>Hikâye</h3>
          <p>Şikayetin başlangıcı, mevsimselliği, çevresel etkenler ve kullanılan ilaçlar ayrıntılı olarak konuşulur.</p>
        </li>
        <li>
          <span class="step-n">2</span>
          <h3>Muayene ve test</h3>
          <p>Gerekli görülürse deri testi, spesifik IgE ya da solunum fonksiyon testi planlanır. Test öncesi hazırlık anlatılır.</p>
        </li>
        <li>
          <span class="step-n">3</span>
          <h3>Adlandırma</h3>
          <p>Bulgular birleştirilir, şikayetin adı ve kaynağı netleştirilir. Sonuçlar sade bir dille açıklanır.</p>
        </li>
        <li>
          <span class="step-n">4</span>
          <h3>Plan ve takip</h3>
          <p>Kaçınma önerileri, ilaç planı ve uygunsa immünoterapi kararı yazılı olarak paylaşılır; kontrol randevusu belirlenir.</p>
        </li>
      </ol>
      <div class="caution">
