      <p>Hakemli dergilerde yayımlanmış <strong>9 bilimsel çalışması</strong> bulunmaktadır. Çalışmalar ağırlıklı olarak alerjik solunum yolu hastalıkları, polen duyarlılığı ve immünoterapi uygulamaları üzerinedir. 2007 yılında düzenlenen ulusal kongrede iki ayrı çalışmayla ödül almıştır.</p>

      <div class="grid-2" style="margin:1.25rem 0">
        <article class="card">
          <span class="badge badge--gold">2007 · Birincilik</span>
          <h3 style="margin-top:.75rem">Zeytin poleni immünoterapisi</h3>
          <p class="sm muted">Ulusal Alerji ve Klinik İmmünoloji Kongresi — bildiri birincilik ödülü. Zeytin poleni duyarlılığı, Ege ve Akdeniz kıyı şeridinde yaygın görülen ve ilkbahar aylarında şikayetleri belirginleştiren bir alerjen kaynağıdır.</p>
        </article>
        <article class="card">
          <span class="badge badge--gold">2007 · Üçüncülük</span>
          <h3 style="margin-top:.75rem">Lateks alerjisi çalışması</h3>
          <p class="sm muted">Ulusal kongre bildiri üçüncülük ödülü. Lateks duyarlılığı özellikle sağlık çalışanları ve sık cerrahi girişim geçirmiş hastalar için önem taşır.</p>
        </article>
      </div>

      <p>Yayınların tam künyeleri, yayın yılları ve dergileri ayrı bir sayfada listelenmiştir. İddia yerine doğrulanabilir kayıt sunmak, bu sitenin temel tercihidir.</p>
      <p><a class="link-arrow" href="/yayinlar-ve-oduller/">Tüm yayınları ve ödülleri künyeleriyle görün</a></p>

      <h2 id="akademik">Akademik ve eğitici görevleri</h2>
      <p>2016 yılında Yeni Yüzyıl Üniversitesi'nde öğretim üyesi olarak göreve başladı. Üniversitedeki görev süresince tıp öğrencilerine ve asistan hekimlere alerjik hastalıklar, astım yönetimi ve immünoterapi konularında ders verdi; poliklinik eğitimlerinde deri testi uygulama ve yorumlama pratiği yürüttü.</p>
      <p>Hastane döneminde Yedikule Göğüs Hastalıkları Eğitim ve Araştırma Hastanesi'nde alerji laboratuvarının kurulması, yalnızca bir cihaz kurulumu değil; test panellerinin seçimi, uygulama protokollerinin yazılması, yardımcı sağlık personelinin eğitilmesi ve sonuçların standart biçimde raporlanması anlamına geliyordu. Bu altyapı çalışması, sonraki yıllarda çok sayıda hastanın aynı standartta test edilebilmesini sağladı.</p>
      <p>Eğitici tarafın hasta için karşılığı şudur: bir konuyu öğrenciye anlatabilen hekim, aynı konuyu hastaya da sade bir dille anlatabilir. Muayenede test sonuçlarının çizilerek, gerektiğinde kâğıda dökülerek açıklanmasının nedeni budur.</p>

      <h2 id="unvan">“Uzm. Dr.” ne anlama geliyor?</h2>
      <p><strong>“Uzm. Dr.”</strong> kısaltması <strong>uzman doktor</strong> anlamına gelir: tıp fakültesinden sonra belirli bir alanda uzmanlık eğitimini tamamlamış hekimi ifade eder. Hasta açısından belirleyici olan bilgi budur — hangi alanda eğitim alındığı ve o alanda ne kadar süredir çalışıldığı.</p>
      <div class="caution">
        <b>İki aşamalı uzmanlık:</b> Dr. Ersoy önce <b>İç Hastalıkları</b> uzmanlığını (2005), ardından <b>Alerji ve Klinik İmmünoloji</b> yan dal uzmanlığını (2009) tamamlamıştır. Yan dal, bir uzmanlık eğitiminin üzerine alınan <b>ikinci bir uzmanlık eğitimidir</b>; alerjik hastalıkları vücudun tümüyle ilişkisi içinde değerlendirebilmeyi sağlar.
      </div>
      <p>Uzmanlık unvanı bir üstünlük iddiası değil, alınan tıp eğitiminin alanını gösteren resmî bir tanımdır. Bu sitede hekimin unvanı, Sağlık Bakanlığı tescilindeki tıbbi uzmanlık biçimiyle kullanılmaktadır.</p>

