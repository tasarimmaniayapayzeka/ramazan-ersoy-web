      <h2 id="cerez-nedir">Çerez nedir?</h2>
      <p>Çerez (cookie), ziyaret ettiğiniz internet sitesi tarafından tarayıcınız aracılığıyla cihazınıza (bilgisayar, telefon, tablet) kaydedilen küçük metin dosyasıdır. Çerezler siteye, örneğin dil tercihinizi hatırlamak, oturumunuzu açık tutmak ya da sitenin hangi bölümlerinin ne sıklıkla ziyaret edildiğini ölçmek gibi işlevler sağlar.</p>
      <p>Çerezler kaynaklarına göre ikiye ayrılır: ziyaret ettiğiniz site tarafından yerleştirilen <strong>birinci taraf çerezleri</strong> ve sitede hizmet sunan başka kuruluşlar (ör. analiz veya reklam sağlayıcıları) tarafından yerleştirilen <strong>üçüncü taraf çerezleri</strong>. Sürelerine göre ise tarayıcı kapatıldığında silinen <strong>oturum çerezleri</strong> ve belirli bir süre cihazda kalan <strong>kalıcı çerezler</strong> vardır.</p>
      <p>Çerezlerin kendisi virüs ya da zararlı yazılım değildir; ancak bazı çerez türleri kişisel veri işleyebildiği için 6698 sayılı Kişisel Verilerin Korunması Kanunu (KVKK) kapsamında değerlendirilir. Bu nedenle zorunlu olmayan çerezler yalnızca açık rızanızla kullanılabilir.</p>

