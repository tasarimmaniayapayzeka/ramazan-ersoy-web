      </ul>
      <p>Verdiğiniz rıza kayıt altına alınır ve dilediğiniz anda, gerekçe göstermeksizin geri alınabilir. Rızanızı geri aldığınızda ilgili kategorideki çerezler yeni ziyaretlerinizde yerleştirilmez; daha önce yerleştirilmiş çerezleri ise aşağıdaki <a href="#tarayici">tarayıcı talimatlarıyla</a> silebilirsiniz.</p>

      <h2 id="consent-mode">Google Consent Mode v2'ye hazırlık</h2>
      <p>Site yayın aşamasında ölçümleme için Google Analytics 4 kullanılması planlanmaktadır. Bu entegrasyon, Google'ın rıza yönetimi çerçevesi olan <strong>Consent Mode v2</strong> ile uyumlu kurulacaktır. Bu çerçevede:</p>
      <ul>
        <li>Rıza sinyalleri (<code>analytics_storage</code>, <code>ad_storage</code>, <code>ad_user_data</code>, <code>ad_personalization</code>) varsayılan olarak <strong>"denied" (reddedildi)</strong> konumunda başlar.</li>
        <li>Siz çerez bandında açık rıza vermedikçe hiçbir ölçümleme veya reklam çerezi yerleştirilmez.</li>
        <li>Rıza verdiğinizde yalnızca onayladığınız kategorilere karşılık gelen sinyaller <strong>"granted" (izin verildi)</strong> konumuna geçer.</li>
        <li>Rızanızı geri aldığınızda sinyaller yeniden "denied" konumuna döner.</li>
      </ul>
      <p>Demo aşamasında bu altyapı henüz devrede değildir; siteye herhangi bir Google ölçümleme kodu yüklenmemektedir.</p>

      <h2 id="tarayici">Çerezleri tarayıcınızdan yönetme</h2>
      <p>Çerez bandından bağımsız olarak, çerezleri her zaman tarayıcınızın ayarlarından da görüntüleyebilir, silebilir veya tamamen engelleyebilirsiniz. Sık kullanılan tarayıcılar için kısa yollar:</p>

      <h3>Google Chrome</h3>
      <ul>
        <li><b>Ayarlar → Gizlilik ve güvenlik → Üçüncü taraf çerezleri</b> yolunu izleyin veya adres çubuğuna <code>chrome://settings/cookies</code> yazın.</li>
        <li>Kayıtlı çerezleri görmek ve silmek için: <b>Ayarlar → Gizlilik ve güvenlik → Site ayarları → Çerezler ve site verileri</b>.</li>
        <li>Belirli bir sitenin çerezlerini silmek için adres çubuğundaki kilit/ayar simgesine tıklayıp <b>Çerezler ve site verileri</b>'ni seçebilirsiniz.</li>
      </ul>

      <h3>Safari</h3>
      <ul>
        <li><b>Mac'te:</b> Safari → Ayarlar → <b>Gizlilik</b> sekmesi → "Tüm çerezleri engelle" seçeneği; kayıtlı verileri görmek için <b>Web Sitesi Verilerini Yönet</b>.</li>
        <li><b>iPhone/iPad'de:</b> Ayarlar → Safari → <b>Gizlilik ve Güvenlik</b> bölümünden çerez ve izleme tercihlerinizi düzenleyebilir, <b>Geçmişi ve Web Sitesi Verilerini Sil</b> ile temizleyebilirsiniz.</li>
      </ul>

      <h3>Mozilla Firefox</h3>
      <ul>
        <li><b>Ayarlar → Gizlilik ve Güvenlik</b> yolunu izleyin veya adres çubuğuna <code>about:preferences#privacy</code> yazın.</li>
        <li><b>Geliştirilmiş İzleme Koruması</b> bölümünden Standart, Katı veya Özel koruma düzeyini seçebilirsiniz.</li>
        <li>Kayıtlı çerezleri silmek için: <b>Çerezler ve Site Verileri → Verileri Temizle</b>.</li>
      </ul>

      <h3>Microsoft Edge</h3>
      <ul>
        <li><b>Ayarlar → Çerezler ve site izinleri → Çerezleri ve site verilerini yönet ve sil</b> yolunu izleyin veya adres çubuğuna <code>edge://settings/content/cookies</code> yazın.</li>
      </ul>

